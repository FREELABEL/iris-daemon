#!/usr/bin/env node
'use strict'

/**
 * iris-portal-record — record a portal flow once on this node, keep it as a Hive script (#187920).
 *
 *   node lib/portal-record-cli.js --url https://portal.example.com/login --name pathways-labs \
 *        --vault pathways-portal [--phi-values sample-record.json] [--records sample-records.json]
 *   node lib/portal-record-cli.js --from raw.spec.ts --name pathways-labs --vault pathways-portal
 *
 * WHY A CLI ON THE NODE. The person doing the flow sits at the node, in a headed browser
 * (Playwright codegen). The raw recording holds what they typed — the portal password, the MFA
 * code, the sample patient — so it is sanitised HERE and the raw file is shredded before anything
 * is written where `iris hive script push` / `hive schedule add` can see it. Only the
 * parameterised script ever exists outside a 0700 temp dir.
 *
 * It writes into the daemon's scripts dir (what `iris hive schedule add <filename>` runs):
 *   <name>.spec.ts  — the parameterised Playwright script (selectors + steps)
 *   <name>.js       — a launcher a schedule can fire: opens the vault credential by NAME, runs the
 *                     spec, and — if <name>.records.json exists — makes it a checkpointed portal
 *                     run (#187919) keyed by name + date, so a re-fire the same day resumes.
 */

const fs = require('fs')
const path = require('path')
const { spawnSync } = require('child_process')
const rec = require('./portal-recorder')

function parseArgs (argv) {
  const out = {}
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i]
    if (!a.startsWith('--')) continue
    const k = a.slice(2)
    const v = argv[i + 1] && !argv[i + 1].startsWith('--') ? argv[++i] : true
    out[k] = v
  }
  return out
}

function defaultScriptsDir () {
  const dataDir = process.env.DAEMON_DATA_DIR || path.join(__dirname, '..', '..', 'daemon-data')
  return path.join(dataDir, 'scripts')
}

/** The launcher a node schedule fires. Pure string so it can be tested without a browser. */
function launcherSource ({ name, vault, daemonDir }) {
  return `// ${name} — launcher for a recorded portal flow (#187920). Generated by iris-portal-record.
// Runs ${name}.spec.ts with the node-vault credential ${vault ? `"${vault}"` : '(none)'} opened by NAME on this machine.
const { spawnSync } = require('child_process')
const fs = require('fs')
const path = require('path')
const DAEMON = ${JSON.stringify(daemonDir)}
const here = __dirname
let env = { ...process.env }
const vault = ${JSON.stringify(vault || null)}
if (vault) {
  try {
    const v = require(path.join(DAEMON, 'lib', 'node-vault.js'))
    env = { ...env, ...v.envForTask(vault, v.getCredential(vault)) }
  } catch (e) {
    console.error('node-vault credential "' + vault + '" unavailable: ' + e.message)
    process.exit(3)
  }
}
// Non-secret sample parameters, if any: { "LAST_NAME": "Sample" } → IRIS_PARAM_LAST_NAME.
const paramsFile = path.join(here, ${JSON.stringify(name + '.params.json')})
if (fs.existsSync(paramsFile)) {
  for (const [k, val] of Object.entries(JSON.parse(fs.readFileSync(paramsFile, 'utf8')))) env['IRIS_PARAM_' + k] = String(val)
}
// #187919: a records file makes this a checkpointed portal run; the run key is name + date so a
// schedule re-fired the same day resumes at the first unfinished record.
const recordsFile = path.join(here, ${JSON.stringify(name + '.records.json')})
if (fs.existsSync(recordsFile)) {
  const pc = require(path.join(DAEMON, 'lib', 'portal-checkpoint.js'))
  const runKey = ${JSON.stringify(name)} + '-' + new Date().toISOString().slice(0, 10)
  const prep = pc.preparePortalRun({ config: { run_key: runKey, records_file: recordsFile } }, here)
  env = { ...env, ...prep.env }
}
const r = spawnSync('npx', ['playwright', 'test', path.join(here, ${JSON.stringify(name + '.spec.ts')}), '--headed', '--reporter=line'], { cwd: here, env, stdio: 'inherit' })
process.exit(r.status === null ? 1 : r.status)
`
}

/** Sanitise a raw recording and write the script + launcher. Returns what was written. */
function saveRecording ({ rawFile, name, vault, phiValues, scriptsDir }) {
  const slug = String(name || '').toLowerCase().replace(/[^a-z0-9-]+/g, '-').replace(/^-+|-+$/g, '')
  if (!slug) throw new Error('--name is required (letters, digits, dashes)')
  const raw = fs.readFileSync(rawFile, 'utf8')
  const out = rec.sanitizeRecording(raw, { name: slug, vault, phiValues })
  fs.mkdirSync(scriptsDir, { recursive: true })
  const specPath = path.join(scriptsDir, `${slug}.spec.ts`)
  const launcherPath = path.join(scriptsDir, `${slug}.js`)
  fs.writeFileSync(specPath, out.script, 'utf8')
  fs.writeFileSync(launcherPath, launcherSource({ name: slug, vault, daemonDir: path.join(__dirname, '..') }), 'utf8')
  return { slug, specPath, launcherPath, params: out.params, removed: out.removed }
}

/** Every string value of a sample record, to strip wherever it appears in the recording. */
function phiValuesFrom (file) {
  if (!file) return []
  const v = JSON.parse(fs.readFileSync(file, 'utf8'))
  const vals = []
  const walk = (x) => {
    if (x === null || x === undefined) return
    if (typeof x === 'object') { Object.values(x).forEach(walk); return }
    vals.push(String(x))
  }
  walk(v)
  return vals
}

let pendingSeal = null

function main (argv) {
  const a = parseArgs(argv)
  if (a.help || (!a.url && !a.from)) {
    console.log('usage: iris-portal-record --url <portal login url> --name <slug> [--vault <node-vault name>] [--phi-values sample.json] [--records records.json [--encrypted-vault <name>]] [--scripts-dir dir]\n       iris-portal-record --from <raw codegen spec> --name <slug> [--vault <name>]')
    return a.help ? 0 : 2
  }
  const scriptsDir = a['scripts-dir'] || defaultScriptsDir()
  let rawFile = a.from
  let shred = false
  if (!rawFile) {
    rawFile = rec.rawRecordingPath()
    shred = true
    console.log('Recording: do the portal flow once in the browser that opens, then close it.')
    const r = spawnSync('npx', rec.codegenArgs({ url: a.url, outFile: rawFile }), { stdio: 'inherit' })
    if (r.status !== 0 || !fs.existsSync(rawFile)) { rec.shredRaw(rawFile); console.error('codegen did not produce a recording'); return 1 }
  }
  try {
    const saved = saveRecording({ rawFile, name: a.name, vault: typeof a.vault === 'string' ? a.vault : null, phiValues: phiValuesFrom(a['phi-values']), scriptsDir })
    if (typeof a.records === 'string' && typeof a['encrypted-vault'] === 'string') {
      // A records file is a list of patients. With an encrypted vault it is sealed there, not
      // copied as plaintext next to the script.
      const ev = require('./encrypted-vault')
      const entry = ev.getEntry(a['encrypted-vault'])
      // The CLI entry point awaits this before exiting (see the bottom of the file).
      pendingSeal = ev.putFile(entry, a.records, { name: `${saved.slug}.records.json`, kind: 'portal-records', tag: `records:${saved.slug}` })
        .then(r => console.log(`  records sealed into vault ${entry.name} (object ${r.fileId}); the source file ${a.records} was NOT deleted — remove it yourself`))
        .catch(e => { console.error(`  could not seal records into vault ${entry.name}: ${e.message}`); process.exitCode = 1 })
    } else if (typeof a.records === 'string') fs.copyFileSync(a.records, path.join(scriptsDir, `${saved.slug}.records.json`))
    const r = saved.removed
    console.log(`Saved ${saved.specPath}`)
    console.log(`  removed: ${r.password} password, ${r.username} username, ${r.otp} one-time code, ${r.param} typed value(s), ${r.echoed} echo(es), ${r.phi_literal} record-looking text, ${r.url_query} URL value(s)`)
    console.log(`  parameters: ${saved.params.map(p => p.name).join(', ') || '(none)'} — set IRIS_PARAM_<NAME>, ${saved.slug}.params.json, or a records file`)
    console.log(`Replay on a schedule:  iris hive schedule add ${saved.slug}.js --cron "0 6 * * *"`)
    console.log(`Replay once now:        iris hive script push ${saved.launcherPath}`)
    return 0
  } finally {
    // The raw recording is the only place the typed values ever existed. Gone either way.
    if (shred) rec.shredRaw(rawFile)
  }
}

if (require.main === module) {
  const code = main(process.argv.slice(2))
  Promise.resolve(pendingSeal).then(() => process.exit(process.exitCode || code))
}

module.exports = { saveRecording, launcherSource, phiValuesFrom, parseArgs, main }
